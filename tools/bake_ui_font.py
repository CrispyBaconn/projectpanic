#!/usr/bin/env python3
# Prepares the menu fonts (platform/ui_font.h): Bangers (titles and buttons) and Lilita One (text), both OFL
# (licenses in platform/fonts/). Each character has two images in the atlas: the fill and the outline (the
# fill widened by R pixels), so the menu draws the black outline and then the letter with the gradient.
# Letters that neither font has (Cyrillic for the body text, Japanese, Chinese) come from a third atlas, "fallback",
# made with Noto Sans CJK Bold (OFL) from the characters actually used in platform/lang/*.json.
# Usage: python3 tools/bake_ui_font.py   (needs Pillow and, for the fallback, Noto Sans CJK:
#        sudo apt install fonts-noto-cjk, or set NOTO_CJK to the path of NotoSansCJK-Bold.ttc)
import glob, io, json, os
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CPS = list(range(32, 127)) + list(range(160, 256)) + [0x2019, 0x2026, 0x20AC, 0x2013, 0x2014, 0x201C, 0x201D, 0x0152, 0x0153]
FONTS = [("display", "Bangers-Regular.ttf", 84, 6), ("body", "LilitaOne-Regular.ttf", 46, 4)]
ATLAS_W = 2048

def has(font, ch): return font.getmask(ch).getbbox() is not None

def bake(name, file, size, R, cps=CPS, pick=None):
    font = ImageFont.truetype(os.path.join(ROOT, "platform", "fonts", file), size) if file else None
    asc, desc = (font or pick(65)).getmetrics()
    glyphs = []
    for cp in cps:
        ch = chr(cp)
        if pick: font = pick(cp)
        if cp != 32 and font.getmask(ch).getbbox() is None: continue
        adv = font.getlength(ch)
        bb = font.getbbox(ch)                       # relative to the top-left point (ascender)
        if cp == 32 or bb[2] <= bb[0]:
            glyphs.append((cp, None, None, 0, 0, adv)); continue
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        im = Image.new("L", (w + 2 * R + 2, h + 2 * R + 2), 0)
        ImageDraw.Draw(im).text((R + 1 - bb[0], R + 1 - bb[1]), ch, font=font, fill=255)
        fill = im
        ol = im.filter(ImageFilter.MaxFilter(2 * R + 1)) if R else im
        # softness of the outline edge
        ol = ol.filter(ImageFilter.GaussianBlur(0.6))
        glyphs.append((cp, fill, ol, bb[0] - R - 1, bb[1] - R - 1, adv))
    # shelf packing: fill and outline of the same letter side by side
    x = y = rowh = 0; place = []
    for g in glyphs:
        if g[1] is None: place.append(None); continue
        w, h = g[1].size
        if x + 2 * w + 2 > ATLAS_W: x = 0; y += rowh + 1; rowh = 0
        place.append((x, y)); x += 2 * w + 2; rowh = max(rowh, h)
    H = y + rowh + 1
    atlas = Image.new("L", (ATLAS_W, H), 0)
    recs = []
    for g, p in zip(glyphs, place):
        cp, fill, ol, ox, oy, adv = g
        if p is None: recs.append((cp, 0, 0, 0, 0, 0, 0, round(adv * 4))); continue
        w, h = fill.size
        atlas.paste(fill, (p[0], p[1])); atlas.paste(ol, (p[0] + w + 1, p[1]))
        recs.append((cp, p[0], p[1], w, h, ox, oy, round(adv * 4)))
    buf = io.BytesIO(); atlas.save(buf, "PNG", optimize=True)
    return dict(name=name, png=buf.getvalue(), recs=recs, asc=asc, desc=desc, size=size, R=R, H=H)

out = ["// generated by tools/bake_ui_font.py - do not edit by hand", "#pragma once", "#include <cstdint>",
       "namespace uifont {",
       "struct Glyph { uint16_t cp, x, y, w, h; int16_t ox, oy; uint16_t adv4; };   // outline at (x + w + 1, y); adv4 = advance * 4",
       "struct Font { const uint8_t* png; unsigned png_size; const Glyph* g; int n; int asc, desc, size, R; };"]
# ---- fallback: characters of the translations missing from one of the two fonts
main = [ImageFont.truetype(os.path.join(ROOT, "platform", "fonts", f[1]), 40) for f in FONTS]
need, ja = set(), set()
for p in glob.glob(os.path.join(ROOT, "platform", "lang", "*.json")):
    txt = "".join(json.load(open(p, encoding="utf-8")).values())
    for ch in txt:
        if ord(ch) > 32 and not all(has(m, ch) for m in main):
            need.add(ord(ch))
            if os.path.basename(p) == "ja.json": ja.add(ord(ch))
jobs = [(f, None, None) for f in FONTS]
noto = os.environ.get("NOTO_CJK") or next((p for p in ["/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc",
        "/usr/share/fonts/noto-cjk/NotoSansCJK-Bold.ttc", "C:/Windows/Fonts/NotoSansCJK-Bold.ttc"] if os.path.exists(p)), None)
if need and noto:
    faces = {}
    for i in range(10):                                   # the .ttc has one face per region: JP for Japanese, SC for the rest
        try: f = ImageFont.truetype(noto, 52, index=i)
        except OSError: break
        fam = f.getname()[0]
        if fam.endswith(" JP"): faces["JP"] = f
        if fam.endswith(" SC"): faces["SC"] = f
    sc, jp = faces.get("SC"), faces.get("JP") or faces.get("SC")
    jobs.append((("fallback", None, 52, 4), sorted(need | {ord("H")}), lambda cp: jp if cp in ja else sc))
    print("fallback:", len(need), "characters from", noto)
elif need:
    print("WARNING: Noto Sans CJK not found, %d characters of the translations will show as '?'" % len(need))
for f, cps, pick in jobs:
    d = bake(*f, cps=cps or CPS, pick=pick)
    b = d["png"]
    out.append(f"static const uint8_t {d['name']}_png[{len(b)}] = {{")
    for i in range(0, len(b), 32): out.append("".join(f"{v}," for v in b[i:i + 32]))
    out.append("};")
    out.append(f"static const Glyph {d['name']}_g[{len(d['recs'])}] = {{")
    out.append(",".join("{%d,%d,%d,%d,%d,%d,%d,%d}" % r for r in d["recs"]))
    out.append("};")
    out.append(f"static const Font {d['name']} = {{{d['name']}_png, {len(b)}, {d['name']}_g, {len(d['recs'])}, {d['asc']}, {d['desc']}, {d['size']}, {d['R']}}};")
    print(d["name"], "atlas", ATLAS_W, "x", d["H"], len(b), "bytes")
if len(jobs) == 2: out.append("static const Font fallback = {nullptr, 0, nullptr, 0, 0, 0, 52, 4};")
out.append("}  // namespace uifont")
open(os.path.join(ROOT, "platform", "ui_font.h"), "w").write("\n".join(out) + "\n")
